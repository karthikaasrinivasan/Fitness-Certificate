const printButton = document.getElementById("printButton");
const downloadButton = document.getElementById("downloadButton");

function printPage() {
  window.print();
}

const { jsPDF } = window.jspdf;

document.addEventListener('DOMContentLoaded', () => {
    const downloadButton = document.getElementById('downloadButton');
    const printButton = document.getElementById('printButton');

    downloadButton.addEventListener('click', () => {
        const doc = new jsPDF({
            orientation: 'p', /*portrait*/
            unit: 'mm',
            format: 'a4'
        });

        const margin = 10;
        const fontSize = 12;

        const title = "FC 1 - Main Auditorium Report";
        const titleWidth = doc.getStringUnitWidth(title) * fontSize / doc.internal.scaleFactor;
        const pageWidth = doc.internal.pageSize.getWidth();
        const titleX = (pageWidth - titleWidth) / 2; //title center
        doc.setFontSize(fontSize + 2); //fontsize for title
        doc.text(title, titleX, margin + fontSize);

        const titleHeight = margin + fontSize + 5; 
        doc.setFontSize(fontSize);
        const yStart = titleHeight + fontSize * 1; 
        const lineSpacing = 8; 
        doc.text("Generated by :", margin, yStart);
        doc.text("Date :", margin, yStart + lineSpacing);
        doc.text("Duration :", margin, yStart + lineSpacing * 2);

        const yContentStart = yStart + lineSpacing * 3 + 10; 
        doc.text("Number of questions with positive (Yes) feedback :", margin, yContentStart);
        const positiveFeedback = [
            "",
            "",
            "",
            "",
            "",
            "",
            "",
            ""
        ];
        //to the pdf (loop)
        positiveFeedback.forEach((item, index) => {
            const questionNumber = `${index + 1}.`;
            const questionX = margin + 5; 
            const questionTextX = margin + 10; 
            doc.text(questionNumber, questionX, yContentStart + (index + 1) * 10);
            doc.text(item, questionTextX, yContentStart + (index + 1) * 10);
        });

        const yAfterPositive = yContentStart + (positiveFeedback.length + 1) * 10;
        doc.text("Number of questions with negative (No) feedback :", margin, yAfterPositive);
        const negativeFeedback = [
            "",
            "",
            "",
            "",
            "",
            "",
            ""
        ];
        negativeFeedback.forEach((item, index) => {
            const questionNumber = `${index + 1}.`;
            doc.text(questionNumber, margin + 5, yAfterPositive + (index + 1) * 10);
            doc.text(item, margin + 10, yAfterPositive + (index + 1) * 10);
        });

        const yAfterNegative = yAfterPositive + (negativeFeedback.length + 1) * 10;
        doc.text("Number of questions with three consecutive negative (No) feedback :", margin, yAfterNegative);
        const consecutiveNegative = [
            "",
            "",
            ""
        ];
        consecutiveNegative.forEach((item, index) => {
            const questionNumber = `${index + 1}.`;
            doc.text(questionNumber, margin + 5, yAfterNegative + (index + 1) * 10);
            doc.text(item, margin + 10, yAfterNegative + (index + 1) * 10);
        });

        doc.save('FC1_Report.pdf');
    });

    printButton.addEventListener('click', () => {
        window.print();
    });
});
